export type IconName = keyof typeof icons;

export function Icon({
  name,
  size = 20,
  color = colors.primaryDeep,
  strokeWidth = 2,
  fill,
}: {
  name: IconName;
  size?: number;
  color?: string;
  strokeWidth?: number;
  fill?: string;
}) {
  const Component = icons[name];
  return <Component color={color} size={size} strokeWidth={strokeWidth} fill={fill ?? 'none'} />;
}
